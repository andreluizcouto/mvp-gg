-- Phase 12-01: auth + monetization storage foundation

create table if not exists users (
    id uuid primary key,
    email text not null unique,
    password_hash text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists auth_sessions (
    session_id uuid primary key,
    user_id uuid not null references users(id) on delete cascade,
    access_token_hash text not null,
    refresh_token_hash text not null,
    access_token_expires_at timestamptz not null,
    refresh_token_expires_at timestamptz not null,
    revoked_at timestamptz null,
    created_at timestamptz not null default now()
);

create unique index if not exists idx_auth_sessions_access_hash
    on auth_sessions(access_token_hash);

create unique index if not exists idx_auth_sessions_refresh_hash
    on auth_sessions(refresh_token_hash);

create index if not exists idx_auth_sessions_user_created
    on auth_sessions(user_id, created_at desc);

create table if not exists entitlements (
    user_id uuid primary key references users(id) on delete cascade,
    plan_tier text not null default 'free',
    analysis_quota integer not null default 0 check (analysis_quota >= 0),
    analyses_consumed integer not null default 0 check (analyses_consumed >= 0),
    analyses_performed integer not null default 0 check (analyses_performed >= 0),
    active boolean not null default true,
    updated_at timestamptz not null default now()
);

create table if not exists analysis_usage (
    id bigint generated by default as identity primary key,
    user_id uuid not null references users(id) on delete cascade,
    operation_id text not null,
    analyses_consumed integer not null default 0 check (analyses_consumed >= 0),
    analyses_performed integer not null default 0 check (analyses_performed >= 0),
    created_at timestamptz not null default now(),
    unique (user_id, operation_id)
);

create index if not exists idx_analysis_usage_user_created
    on analysis_usage(user_id, created_at desc);

create table if not exists user_identities (
    id bigint generated by default as identity primary key,
    user_id uuid not null references users(id) on delete cascade,
    riot_id text not null,
    created_at timestamptz not null default now(),
    unique (user_id, riot_id)
);

create index if not exists idx_user_identities_riot_id
    on user_identities(riot_id);
